func TestPhraseDiffers(t *testing.T) {
	dict := miniDict()
	tests := []struct {
		phrase   string
		readings []string
		want     bool
	}{
		{"重庆", []string{"chóng", "qìng"}, true},  // 重 换了读音
		{"重庆", []string{"zhòng", "qìng"}, false}, // 与默认读音一致
		{"中国", []string{"zhōng", "guó"}, false},  // 中 的首音就是默认音
		{"中国", []string{"zhòng", "guó"}, true},   // 中 换了读音
		{"一下", []string{"yī", "xià"}, false},
		{"一下", []string{"yí", "xià"}, true}, // 变调也算不同
		{"下子", []string{"xià", "zǐ"}, true},
		{"下子", []string{"xià", "zi"}, false}, // 轻声与三声必须区分开
	}
	for _, tt := range tests {
		runes := []rune(tt.phrase)
		if got := phraseDiffers(runes, tt.readings, dict); got != tt.want {
			t.Errorf("phraseDiffers(%q, %v) = %v, want %v", tt.phrase, tt.readings, got, tt.want)
		}
	}
}

func TestHeadKey(t *testing.T) {
	tests := []struct{ in, want string }{
		{"重庆", "重庆"},
		{"一下子", "一下"},
		{"中国共产党为公布国共合作宣言", "中国"},
		{"〇一", "〇一"},
		{"𠈌人", "𠈌人"}, // BMP 之外的字也按 rune 切
	}
	for _, tt := range tests {
		if got := headKey(tt.in); got != tt.want {
			t.Errorf("headKey(%q) = %q, want %q", tt.in, got, tt.want)
		}
	}
}

func TestEmitPhrases(t *testing.T) {
	dir := t.TempDir()
	old, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	if err := os.Chdir(dir); err != nil {
		t.Fatal(err)
	}
	defer func() {
		if err := os.Chdir(old); err != nil {
			t.Fatal(err)
		}
	}()

	entries := []phraseEntry{
		{phrase: "重庆", readings: "chóng qìng", differs: true},
		// 读音与逐字默认读音一致的词组不写读音，只留空的读音字段。
		{phrase: "一下子", readings: "yī xià zi"},
	}
	if err := emitPhrases(entries, "9.9.9"); err != nil {
		t.Fatal(err)
	}
	src, err := os.ReadFile(phraseOut)
	if err != nil {
		t.Fatal(err)
	}
	body := string(src)
	for _, want := range []string{
		"// Code generated by cmd/gendata from data/phrase_pinyin.txt; DO NOT EDIT.",
		"9.9.9",
		"package pinyin",
		`"重庆|chóng qìng|一下子||"`,
	} {
		if !strings.Contains(body, want) {
			t.Errorf("生成结果缺少 %q\n%s", want, body)
		}
	}
	if strings.Contains(body, "yī xià zi") {
		t.Errorf("读音与逐字默认读音一致的词组不该写读音\n%s", body)
	}
}

