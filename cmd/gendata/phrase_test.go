// writeTemp 把内容写进临时目录，返回文件路径。
func writeTemp(t *testing.T, name, content string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), name)
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
	return path
}

// miniDict 是一份够用的测试字典：默认读音取首个。
func miniDict() map[rune][]string {
	return map[rune][]string{
		'重': {"zhòng", "chóng"},
		'庆': {"qìng"},
		'一': {"yī", "yí"},
		'下': {"xià"},
		'子': {"zi", "zǐ"},
		'个': {"gè"},
		'人': {"rén"},
		'中': {"zhōng", "zhòng"},
		'国': {"guó"},
	}
}

func TestBuildPhrases(t *testing.T) {
	src := strings.Join([]string{
		"# version: 9.9.9",
		"重庆: chóng qìng",     // 与逐字默认读音不同
		"一个: yí gè",          // 变调，同样算不同
		"中国人: zhōng guó rén", // 与逐字默认读音一致
		"一下子: yī xià zi",     // 与逐字默认读音一致
		"下子: xià zǐ",         // 与逐字默认读音不同
		"重: chóng",           // 不足两字，跳过
		"重庆: chóng qìng",     // 重复且读音相同，跳过
		"重庆庆: chóng qìng",    // 音节数与字数不符，跳过
		"重Q: zhòng q",        // 含未收录字，跳过
		"中国: zhōng qā",       // 非规范音节，跳过
	}, "\n")

	got, st, err := buildPhrases(miniDict(), writeTemp(t, "phrase.txt", src))
	if err != nil {
		t.Fatal(err)
	}

	phrases := make([]string, 0, len(got))
	for _, e := range got {
		phrases = append(phrases, e.phrase)
	}
	// 整表收录，输出按「前两个字、字数从多到少」排列：
	// 一下 < 一个 < 下子 < 中国 < 重庆。
	want := []string{"一下子", "一个", "下子", "中国人", "重庆"}
	if strings.Join(phrases, ",") != strings.Join(want, ",") {
		t.Errorf("收录词组 = %v, want %v（数组已按前两字、字数降序排列）", phrases, want)
	}

	if st.total != 10 {
		t.Errorf("total = %d, want 10", st.total)
	}
	if st.kept != 5 || st.excepted != 3 {
		t.Errorf("kept=%d excepted=%d, want 5/3", st.kept, st.excepted)
	}
	if st.same != 2 {
		t.Errorf("same = %d, want 2", st.same)
	}
	if st.skipped != 5 {
		t.Errorf("skipped = %d, want 5", st.skipped)
	}
	if st.maxRunes != 3 {
		t.Errorf("maxRunes = %d, want 3", st.maxRunes)
	}
	for _, reason := range []string{
		"不足两字", "重复词组（读音相同）", "音节数与字数不符", "含未收录字", "非规范音节",
	} {
		if st.reasons[reason] != 1 {
			t.Errorf("跳过原因 %q 计数 = %d, want 1", reason, st.reasons[reason])
		}
	}
}

func TestBuildPhrasesSortOrder(t *testing.T) {
	// 同一个前两字的词组必须连续，且桶内按字数降序——运行时 phraseIndex 依赖这一点。
	got, _, err := buildPhrases(miniDict(), "../../data/phrase_pinyin.txt")
	if err != nil {
		t.Fatal(err)
	}
	for i := 1; i < len(got); i++ {
		hi, hj := headKey(got[i-1].phrase), headKey(got[i].phrase)
		if hi > hj {
			t.Fatalf("第 %d 条起前两字逆序: %q > %q", i, hi, hj)
		}
		if hi == hj {
			li := utf8.RuneCountInString(got[i-1].phrase)
			lj := utf8.RuneCountInString(got[i].phrase)
			if li < lj {
				t.Fatalf("同一个前两字 %q 内未按字数降序: %q 在 %q 之前", hi, got[i-1].phrase, got[i].phrase)
			}
		}
	}
}

