// TestShippedPhraseDataIsConsistent 校验仓库里生成出来的词组表与源数据一致。
func TestShippedPhraseDataIsConsistent(t *testing.T) {
	got, st, err := buildPhrases(loadShippedDict(t), "../../data/phrase_pinyin.txt")
	if err != nil {
		t.Fatal(err)
	}
	if st.kept != len(got) {
		t.Errorf("st.kept = %d, 实际 %d", st.kept, len(got))
	}
	if st.excepted+st.same != st.kept {
		t.Errorf("excepted(%d) + same(%d) != kept(%d)", st.excepted, st.same, st.kept)
	}
	if st.total != st.kept+st.skipped {
		t.Errorf("total(%d) != kept(%d) + skipped(%d)", st.total, st.kept, st.skipped)
	}
	if len(st.conflicts) != st.reasons["重复词组（读音冲突）"] {
		t.Errorf("conflicts 有 %d 条，跳过计数是 %d", len(st.conflicts), st.reasons["重复词组（读音冲突）"])
	}
	if len(got) < 400000 {
		t.Fatalf("只收录了 %d 条词组，源数据可能不完整", len(got))
	}
}

// loadShippedDict 用生成器自己的流程还原出仓库中的字典，供一致性测试使用。
func loadShippedDict(t *testing.T) map[rune][]string {
	t.Helper()
	all, err := parseReadings("../../data/pinyin.txt")
	if err != nil {
		t.Fatal(err)
	}
	common, err := parseReadings("../../data/kMandarin_8105.txt")
	if err != nil {
		t.Fatal(err)
	}
	merged := make(map[rune][]string, len(all))
	for r, pys := range all {
		if inScope(r, common) {
			merged[r] = pys
		}
	}
	for r, pys := range common {
		if _, ok := merged[r]; !ok {
			merged[r] = pys
		}
	}
	if _, err := applyOverrides(merged, "../../data/overrides.txt"); err != nil {
		t.Fatal(err)
	}
	return merged
}
